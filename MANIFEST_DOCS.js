/**
 * ============================================================
 * Image Extractor - Chrome 扩展 manifest.json 配置说明
 * ============================================================
 * 
 * 由于 JSON 格式不支持注释，此文件用于解释 manifest.json 的各项配置
 * 
 * ============================================================
 * 基本信息
 * ============================================================
 * 
 * manifest_version: 3
 *   - 使用 Manifest V3 规范（Chrome 推荐的最新版本）
 *   - V3 使用 Service Worker 替代 Background Page
 *   - V3 有更好的安全性和性能
 * 
 * name: "Image Extractor"
 *   - 扩展在 Chrome 商店和扩展管理页面显示的名称
 * 
 * version: "1.1.0"
 *   - 扩展版本号，格式为 主版本.次版本.修订号
 *   - 每次发布更新时需要递增
 * 
 * description: "从多个标签页提取图片..."
 *   - 扩展的简短描述，显示在扩展管理页面
 * 
 * ============================================================
 * 权限配置 (permissions)
 * ============================================================
 * 
 * activeTab:
 *   - 允许访问用户当前激活的标签页
 *   - 比请求所有标签页权限更安全
 * 
 * tabs:
 *   - 允许查询和操作浏览器标签页
 *   - 用于获取所有打开的标签页列表
 *   - 用于获取标签页的 URL 和标题
 * 
 * downloads:
 *   - 允许使用 chrome.downloads API
 *   - 用于下载图片到本地
 *   - 支持指定下载路径和文件名
 * 
 * scripting:
 *   - 允许使用 chrome.scripting API
 *   - 用于向网页注入脚本
 *   - 用于提取网页中的图片
 * 
 * storage:
 *   - 允许使用 chrome.storage API
 *   - 用于保存用户设置（筛选条件、列数等）
 *   - 数据在浏览器关闭后仍然保留
 * 
 * ============================================================
 * 主机权限 (host_permissions)
 * ============================================================
 * 
 * <all_urls>:
 *   - 允许扩展访问所有网站
 *   - 需要此权限才能从任意网页提取图片
 *   - 在 V3 中，主机权限需要单独声明
 * 
 * ============================================================
 * 扩展图标配置 (action)
 * ============================================================
 * 
 * default_icon:
 *   - 定义工具栏中显示的扩展图标
 *   - 需要提供不同尺寸以适应不同显示密度
 *   - 16x16: 工具栏图标
 *   - 48x48: 扩展管理页面图标
 *   - 128x128: Chrome 商店图标
 * 
 * default_title:
 *   - 鼠标悬停在扩展图标上时显示的提示文字
 * 
 * ============================================================
 * 后台脚本配置 (background)
 * ============================================================
 * 
 * service_worker: "scripts/background.js"
 *   - 指定后台 Service Worker 脚本路径
 *   - Service Worker 在需要时启动，空闲时休眠
 *   - 负责处理点击事件和下载请求
 * 
 * ============================================================
 * 扩展图标 (icons)
 * ============================================================
 * 
 * 定义扩展在不同场景下使用的图标
 * - 16x16: 工具栏、上下文菜单
 * - 48x48: 扩展管理页面
 * - 128x128: Chrome 商店、安装对话框
 */
